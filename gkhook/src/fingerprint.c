int verify_fingerprint(const char* exe_path,
                       int (*peek)(uintptr_t addr, unsigned char* out, size_t n)) {
  struct stat st;
  if (stat(exe_path, &st) != 0 || st.st_size != CHITU_SIZE) return 0;  // before any peek
  for (size_t i = 0; i < sizeof windows / sizeof windows[0]; i++) {
    unsigned char got[16];
    if (peek(windows[i].addr, got, sizeof got) != 0) return 0;
    if (memcmp(got, windows[i].bytes, sizeof got) != 0) return 0;
  }
  return 1;
}

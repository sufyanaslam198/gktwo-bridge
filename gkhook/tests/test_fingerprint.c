#define NK (sizeof K / sizeof K[0])

static int calls, flip_idx = -1, fail_peek;

static int peek_table(uintptr_t a, unsigned char* out, size_t n) {
  calls++;
  if (fail_peek) return -1;
  for (size_t i = 0; i < NK; i++)
    if (K[i].addr == a && n == 16) {
      memcpy(out, K[i].b, 16);
      if ((int)i == flip_idx) out[7] ^= 1;
      return 0;
    }
  return -1;
}

static int peek_real(uintptr_t a, unsigned char* out, size_t n) {
  FILE* f = fopen(REAL_CHITU, "rb");
  if (!f) return -1;
  int ok = fseek(f, (long)(a - 0x10000), SEEK_SET) == 0 && fread(out, 1, n, f) == n;
  fclose(f);
  return ok ? 0 : -1;
}

static char* mkfile(long size, char* tmpl) {
  int fd = mkstemp(tmpl);
  if (fd < 0 || ftruncate(fd, size) != 0) { perror("mkfile"); exit(2); }
  close(fd);
  return tmpl;
}

static int fails;
#define CHECK(c) do { if (!(c)) { fprintf(stderr, "FAIL line %d: %s\n", __LINE__, #c); fails++; } } while (0)

static void test_fingerprint_match(const char* good) {
  calls = 0; flip_idx = -1; fail_peek = 0;
  CHECK(verify_fingerprint(good, peek_table) == 1);
  CHECK(calls == (int)NK);
}

static void test_fingerprint_mismatch_refuses(const char* good, const char* bad) {
  for (int i = 0; i < (int)NK; i++) {  // flip one byte in each window in turn
    flip_idx = i; fail_peek = 0;
    CHECK(verify_fingerprint(good, peek_table) == 0);
  }
  flip_idx = -1; fail_peek = 1;  // unreadable memory refuses
  CHECK(verify_fingerprint(good, peek_table) == 0);
  fail_peek = 0; calls = 0;      // wrong size: refuse without peeking
  CHECK(verify_fingerprint(bad, peek_table) == 0);
  CHECK(calls == 0);
  CHECK(verify_fingerprint("/nonexistent/chitu", peek_table) == 0);
  CHECK(calls == 0);
}

static void test_fingerprint_real_binary(void) {
  if (access(REAL_CHITU, R_OK) != 0) { puts("SKIP real chitu binary not present"); return; }
  CHECK(verify_fingerprint(REAL_CHITU, peek_real) == 1);
}

int main(void) {
  char g[] = "/tmp/gkfp-good-XXXXXX", b[] = "/tmp/gkfp-bad-XXXXXX";
  mkfile(SIZE, g); mkfile(SIZE + 1, b);
  test_fingerprint_match(g);
  test_fingerprint_mismatch_refuses(g, b);
  test_fingerprint_real_binary();
  unlink(g); unlink(b);
  if (fails) return 1;
  puts("test_fingerprint OK");
  return 0;
}
